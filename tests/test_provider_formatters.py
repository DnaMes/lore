def test_claude_file_operation_summary_can_be_disabled():
    session = _session(
        Tool.CLAUDE_CODE,
        [
            _msg(
                Role.ASSISTANT,
                "\n".join(
                    [
                        "The file /tmp/one.py has been updated.",
                        "The file /tmp/two.py has been updated.",
                        "The file /tmp/three.py has been created.",
                    ]
                ),
            )
        ],
    )

    normalize_session_messages_for_display(
        session,
        noise_rules={
            "claude-code": {
                "claude_summarize_file_operations": False,
                "claude_strip_command_xml": True,
            },
            "default": {"strip_ansi_sequences": True},
        },
    )

    assert "File operations summary" not in session.messages[0].content
    assert "The file /tmp/one.py has been updated." in session.messages[0].content


def test_toc_labels_strip_leading_bracket_metadata():
    session = _session(
        Tool.OPENCODE,
        [
            _msg(Role.USER, "[search-model] [Image 1] Bitte mach das sauber"),
            _msg(Role.ASSISTANT, "Done"),
        ],
    )

    toc = enrich_session_for_detail(
        session,
        session_meta={},
        format_message_content_fn=lambda value: value,
        format_tool_calls_fn=lambda value: str(value),
        format_thinking_fn=lambda value: value,
    )

    assert toc
    assert toc[0]["text"] == "Bitte mach das sauber"


