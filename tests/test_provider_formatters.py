from datetime import datetime

from lore.core.models import Role, Tool, UnifiedMessage, UnifiedSession
from lore.interfaces.web_services import (
    enrich_session_for_detail,
    normalize_session_messages_for_display,
)


def _msg(role: Role, content: str) -> UnifiedMessage:
    return UnifiedMessage(role=role, content=content, timestamp=datetime(2026, 3, 4, 12, 0, 0))


def _session(tool: Tool, messages):
    return UnifiedSession(
        tool=tool,
        session_id="ses-test",
        created_at=datetime(2026, 3, 4, 12, 0, 0),
        last_updated=datetime(2026, 3, 4, 12, 5, 0),
        messages=messages,
    )


def test_claude_display_formatter_strips_command_xml_tags():
    session = _session(
        Tool.CLAUDE_CODE,
        [_msg(Role.ASSISTANT, "<command-name>login</command-name> done")],
    )

    normalize_session_messages_for_display(session)

    assert "<command-name>" not in session.messages[0].content
    assert "done" in session.messages[0].content


def test_opencode_display_formatter_strips_caveat_prefix_for_user():
    session = _session(
        Tool.OPENCODE,
        [
            _msg(
                Role.USER,
                "Caveat: the messages below were generated by the user while running local commands\nPlease fix this pipeline",
            )
        ],
    )

    normalize_session_messages_for_display(session)

    assert "Caveat:" not in session.messages[0].content
    assert "Please fix this pipeline" in session.messages[0].content


def test_opencode_assistant_file_update_noise_is_summarized():
    session = _session(
        Tool.OPENCODE,
        [
            _msg(
                Role.ASSISTANT,
                "\n".join(
                    [
                        "The file /tmp/a.py has been updated.",
                        "The file /tmp/b.py has been updated.",
                        "The file /tmp/c.py has been created.",
                    ]
                ),
            )
        ],
    )

    normalize_session_messages_for_display(session)

    assert "File operations summary" in session.messages[0].content
    assert "updated: `/tmp/a.py`" in session.messages[0].content


